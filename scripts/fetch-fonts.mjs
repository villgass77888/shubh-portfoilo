/**
 * Self-hosts the site's fonts: downloads the exact WOFF2 subsets Google Fonts serves for the
 * families below into public/fonts/ and writes src/styles/fonts.css with the same @font-face
 * rules (unicode-range kept, so a browser only fetches the subsets a page uses).
 * One-off: run `node scripts/fetch-fonts.mjs` again only when a family changes.
 */
import fs from 'fs';
import path from 'path';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Anton&family=Archivo:ital,wdth,wght@0,62..125,100..900;1,62..125,100..900&family=Space+Mono:wght@400;700&family=Caveat:wght@400;700&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36';
const OUT = path.join(process.cwd(), 'public/fonts');
/** Subsets the site's text can need (everything else on the page is Latin) */
const KEEP = ['latin', 'latin-ext'];

const css = await (await fetch(CSS_URL, { headers: { 'User-Agent': UA } })).text();
fs.mkdirSync(OUT, { recursive: true });

const blocks = [...css.matchAll(/\/\* ([a-z-]+) \*\/\s*(@font-face\s*{[^}]+})/g)].filter((m) => KEEP.includes(m[1]));
if (!blocks.length) throw new Error('no @font-face blocks found: did the Google Fonts CSS format change?');

const seen = new Map();
const rules = [];
for (const [, subset, rule] of blocks) {
  const url = /url\((https:[^)]+\.woff2)\)/.exec(rule)?.[1];
  const family = /font-family:\s*'([^']+)'/.exec(rule)?.[1];
  const style = /font-style:\s*(\w+)/.exec(rule)?.[1];
  const weight = /font-weight:\s*([\d ]+)/.exec(rule)?.[1].trim().replace(/\s+/g, '-');
  if (!url || !family) continue;
  let file = seen.get(url);
  if (!file) {
    file = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${weight}-${subset}.woff2`;
    seen.set(url, file);
    fs.writeFileSync(path.join(OUT, file), Buffer.from(await (await fetch(url)).arrayBuffer()));
  }
  rules.push(`/* ${family} ${style} ${weight} ✦ ${subset} */\n${rule.replace(url, `/fonts/${file}`)}`);
}

fs.writeFileSync(
  path.join(process.cwd(), 'src/styles/fonts.css'),
  `/* Generated by scripts/fetch-fonts.mjs: the site's fonts, self-hosted from /fonts. */\n\n${rules.join('\n\n')}\n`,
);
console.log(`fonts: ${seen.size} files in public/fonts, ${rules.length} @font-face rules`);
console.log([...seen.values()].map((f) => `  ${f}  ${(fs.statSync(path.join(OUT, f)).size / 1024).toFixed(0)} KB`).join('\n'));
